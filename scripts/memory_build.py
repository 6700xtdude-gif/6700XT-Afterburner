#!/usr/bin/env python3
"""Build the machine-readable memory index and a health report.

This is the "self-building" half of the memory framework. It never invents facts
and never rewrites the curated ledger. It scans what exists, records provenance,
and reports the four failure modes that actually rot a memory system:

  1. ORPHANS      files nothing links to and no agent will ever read
  2. STALE        docs claimed as current that have not been touched in N days
  3. UNSOURCED    numbers in DIGEST.md that appear in no benchmark artifact
  4. ARCHIVE      docs that are negative results or superseded, still in context

Outputs (both regenerated every run, never hand-edited):

  MEMORY/INDEX.json    machine index: every artifact, kind, sha256, title, summary
  MEMORY/HEALTH.md    human report of the four failure modes

Usage:
    python scripts/memory_build.py
    python scripts/memory_build.py --stale-days 14
    python scripts/memory_build.py --check      # exit 1 if health has blockers

Design rule: the builder reports, the human decides. It does not delete, move, or
rewrite anything except its own two outputs.
"""

import argparse
import datetime
import hashlib
import json
import os
import re
import sys

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MEMORY_DIR = os.path.join(REPO_ROOT, "MEMORY")
INDEX_PATH = os.path.join(MEMORY_DIR, "INDEX.json")
HEALTH_PATH = os.path.join(MEMORY_DIR, "HEALTH.md")

GENERATED_MARKER = "<!-- generated by scripts/memory_build.py; do not edit by hand -->"

# (kind, directory relative to repo, filename regex)
SOURCES = [
    ("hardware", "MEMORY", r"^RAM_.*\.json$"),
    ("benchmark", "MEMORY", r"^(?!RAM_|INDEX).*\.json$"),
    ("bench-report", os.path.join("bench", "reports"), r"^benchmark_.*\.json$"),
    ("ledger", "MEMORY", r"^(DIGEST|EXPERIMENT_LOG|LESSONS|GAPS_AND_HYPOTHESES|PROTOCOL|FRAMEWORK)\.md$"),
    ("archive", os.path.join("MEMORY", "ARCHIVE"), r".*\.md$"),
    ("notebook", "NOTEBOOK", r".*\.md$"),
    ("doc", "docs", r".*\.md$"),
    ("patch", "patches", r".*\.patch$"),
    ("test", "tests", r"^test_.*\.py$"),
    ("script", "scripts", r".*\.(ps1|py)$"),
    ("bench-tool", "bench", r"^[a-z_]+\.py$"),
]

NEGATIVE_MARKERS = [
    "negative result", "superseded", "deprecated", "abandoned", "failed approach",
    "does not work", "did not work", "dead end", "rejected",
]

NUM_RE = re.compile(r"\b\d+\.\d{2,}\b")


def rel(path):
    return os.path.relpath(path, REPO_ROOT).replace("\\", "/")


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def read(path):
    with open(path, "r", encoding="utf-8", errors="replace") as fh:
        return fh.read()


def title_and_summary(text, fallback):
    """First markdown heading as title, first prose line as summary."""
    title = fallback
    summary = ""
    lines = text.splitlines()
    for i, line in enumerate(lines):
        s = line.strip()
        if s.startswith("# "):
            title = s[2:].strip()
            for nxt in lines[i + 1:]:
                n = nxt.strip()
                if n and not n.startswith("#") and not n.startswith("|") and not n.startswith("```"):
                    summary = n.lstrip("> ").strip()
                    break
            break
    if not summary:
        for line in lines:
            s = line.strip()
            if s and not s.startswith("#") and not s.startswith("```"):
                summary = s.lstrip("> ").strip()
                break
    return title[:120], summary[:200]


def scan(stale_days):
    artifacts = []
    seen = set()
    now = datetime.datetime.now()
    for kind, subdir, pattern in SOURCES:
        base = os.path.join(REPO_ROOT, subdir)
        if not os.path.isdir(base):
            continue
        rx = re.compile(pattern)
        for name in sorted(os.listdir(base)):
            if not rx.match(name):
                continue
            path = os.path.join(base, name)
            if not os.path.isfile(path) or path in seen:
                continue
            seen.add(path)
            stat = os.stat(path)
            age = (now - datetime.datetime.fromtimestamp(stat.st_mtime)).days
            entry = {
                "path": rel(path),
                "kind": kind,
                "bytes": stat.st_size,
                "ageDays": age,
                "sha256": sha256(path),
                "title": "",
                "summary": "",
            }
            if name.endswith((".md", ".py", ".ps1")):
                text = read(path)
                entry["title"], entry["summary"] = title_and_summary(text, name)
                entry["generated"] = GENERATED_MARKER in text
            else:
                entry["title"] = name
                entry["generated"] = False
            entry["stale"] = age > stale_days
            artifacts.append(entry)
    return artifacts


def find_orphans(artifacts):
    """Prose that no curated entry point links to.

    Only `doc` and `notebook` files are judged. Scripts, tests, patches and
    benchmark JSON are tooling and evidence - they are read on demand, not
    discovered by browsing, so an inbound link is not the right test for them.
    Generated files do not count as references, or the catalog would hide itself.
    """
    text_cache = {}
    for a in artifacts:
        if a["path"].endswith((".md", ".py", ".ps1", ".patch")) and not a.get("generated"):
            text_cache[a["path"]] = read(os.path.join(REPO_ROOT, a["path"]))
    orphans = []
    for a in artifacts:
        if a["kind"] not in ("doc", "notebook"):
            continue
        name = os.path.basename(a["path"])
        referenced = False
        for other_path, body in text_cache.items():
            if other_path == a["path"]:
                continue
            if name in body or a["path"] in body:
                referenced = True
                break
        if not referenced:
            orphans.append(a["path"])
    return orphans


def collect_json_numbers(artifacts):
    """Every 2+ decimal number appearing anywhere in a benchmark/hardware JSON."""
    numbers = set()
    for a in artifacts:
        if a["kind"] not in ("benchmark", "hardware", "bench-report"):
            continue
        try:
            data = json.loads(read(os.path.join(REPO_ROOT, a["path"])))
        except (ValueError, OSError):
            continue

        def walk(node):
            if isinstance(node, dict):
                for v in node.values():
                    walk(v)
            elif isinstance(node, list):
                for v in node:
                    walk(v)
            elif isinstance(node, float):
                numbers.add(f"{node:.2f}")
                numbers.add(f"{node:.3f}")
            elif isinstance(node, str):
                for m in NUM_RE.findall(node):
                    numbers.add(m)

        walk(data)
    return numbers


def find_unsourced(artifacts):
    digest_path = os.path.join(MEMORY_DIR, "DIGEST.md")
    if not os.path.isfile(digest_path):
        return []
    claimed = set(NUM_RE.findall(read(digest_path)))
    sourced = collect_json_numbers(artifacts)
    return sorted(claimed - sourced)


def find_archive_candidates(artifacts):
    hits = []
    for a in artifacts:
        if a["kind"] in ("archive", "test"):
            continue
        haystack = f"{a['title']} {a['summary']}".lower()
        for marker in NEGATIVE_MARKERS:
            if marker in haystack:
                hits.append((a["path"], marker))
                break
    return hits


def fingerprint(artifacts, stale_days):
    """Stable hash of the inputs, so output is a pure function of content.

    A generated file that changes on every run would make a clean git tree
    impossible, and the conformance gate checks for a clean tree. So there is no
    timestamp here - only a hash of what was read.
    """
    payload = json.dumps(
        {"staleDays": stale_days, "inputs": [(a["path"], a["sha256"]) for a in artifacts]},
        sort_keys=True,
    )
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def build(stale_days, check_only=False):
    artifacts = scan(stale_days)
    orphans = find_orphans(artifacts)
    unsourced = find_unsourced(artifacts)
    archive_candidates = find_archive_candidates(artifacts)
    stale = [a["path"] for a in artifacts if a["stale"] and a["kind"] in ("ledger", "notebook", "doc")]
    fp = fingerprint(artifacts, stale_days)

    index = {
        "_generated": GENERATED_MARKER,
        "inputFingerprint": fp,
        "staleDays": stale_days,
        "counts": {},
        "artifacts": artifacts,
    }
    for a in artifacts:
        index["counts"][a["kind"]] = index["counts"].get(a["kind"], 0) + 1

    os.makedirs(MEMORY_DIR, exist_ok=True)
    with open(INDEX_PATH, "w", encoding="utf-8") as fh:
        json.dump(index, fh, indent=2)
        fh.write("\n")

    lines = [
        GENERATED_MARKER,
        "# Memory Health",
        "",
        f"Input fingerprint `{fp}`. Staleness threshold {stale_days} days.",
        "",
        "## Inventory",
        "",
        "| Kind | Count |",
        "|---|---|",
    ]
    for kind in sorted(index["counts"]):
        lines.append(f"| {kind} | {index['counts'][kind]} |")

    lines += ["", f"## Orphans ({len(orphans)})", "",
              "Files nothing links to. Either link them from `MEMORY/DIGEST.md`, or archive them.", ""]
    lines += [f"- `{p}`" for p in orphans] or ["None."]

    lines += ["", f"## Stale ({len(stale)})", "",
              f"Ledger/notebook/doc files untouched for more than {stale_days} days.", ""]
    lines += [f"- `{p}`" for p in stale] or ["None."]

    lines += ["", f"## Unsourced numbers ({len(unsourced)})", "",
              "Numbers in `DIGEST.md` that appear in no benchmark or hardware JSON.",
              "Each one is a claim with no artifact behind it.", ""]
    lines += [f"- `{n}`" for n in unsourced[:40]] or ["None."]

    lines += ["", f"## Archive candidates ({len(archive_candidates)})", "",
              "Docs whose title or summary reads as a negative result or superseded approach.",
              "Move these to `MEMORY/ARCHIVE/` so they stop loading into agent context.", ""]
    lines += [f"- `{p}` ({marker})" for p, marker in archive_candidates] or ["None."]

    with open(HEALTH_PATH, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines) + "\n")

    print(f"index   {rel(INDEX_PATH)}  ({len(artifacts)} artifacts)")
    print(f"health  {rel(HEALTH_PATH)}")
    print(f"orphans {len(orphans)}   stale {len(stale)}   unsourced {len(unsourced)}   archive {len(archive_candidates)}")

    if check_only and (len(orphans) > 0 or len(unsourced) > 0):
        return 1
    return 0


def main():
    ap = argparse.ArgumentParser(description="Build MEMORY/INDEX.json and MEMORY/HEALTH.md.")
    ap.add_argument("--stale-days", type=int, default=30, help="Age in days before a doc is stale (default 30)")
    ap.add_argument("--check", action="store_true", help="Exit 1 if there are orphans or unsourced numbers")
    args = ap.parse_args()
    return build(args.stale_days, args.check)


if __name__ == "__main__":
    sys.exit(main())
