"""Tests for the self-building memory framework.

These verify that the builder is deterministic, that it reports rather than
rewrites, and that the framework's own artifacts exist. They do not test the
model or the GPU.

    python -m unittest tests.test_memory_framework -v
"""

import hashlib
import importlib.util
import json
import os
import unittest

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BUILDER = os.path.join(REPO_ROOT, "scripts", "memory_build.py")


def load_builder():
    spec = importlib.util.spec_from_file_location("memory_build", BUILDER)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def digest_hash():
    path = os.path.join(REPO_ROOT, "MEMORY", "DIGEST.md")
    with open(path, "rb") as fh:
        return hashlib.sha256(fh.read()).hexdigest()


class TestFrameworkArtifacts(unittest.TestCase):
    def test_framework_doc_exists(self):
        path = os.path.join(REPO_ROOT, "MEMORY", "FRAMEWORK.md")
        self.assertTrue(os.path.isfile(path))
        body = open(path, encoding="utf-8").read()
        for section in ("Where it went wrong", "bare-metal standard",
                        "safe to carry over", "Forgetting the bad"):
            self.assertIn(section, body)

    def test_archive_rule_exists(self):
        path = os.path.join(REPO_ROOT, "MEMORY", "ARCHIVE", "README.md")
        self.assertTrue(os.path.isfile(path))
        self.assertIn("Archive candidates", open(path, encoding="utf-8").read())

    def test_session_scripts_exist(self):
        for name in ("session_start.ps1", "session_end.ps1"):
            self.assertTrue(os.path.isfile(os.path.join(REPO_ROOT, "scripts", name)), name)

    def test_clean_start_doc_exists(self):
        path = os.path.join(REPO_ROOT, "docs", "CLEAN_START.md")
        self.assertTrue(os.path.isfile(path))
        body = open(path, encoding="utf-8").read()
        self.assertIn("Definition of done", body)
        self.assertIn("96gb-4dimm", body)


class TestBuilderIsDeterministic(unittest.TestCase):
    """A generated file that changes on every run breaks the clean-tree gate."""

    def test_two_runs_produce_identical_index(self):
        mod = load_builder()
        mod.build(30)
        first = open(os.path.join(REPO_ROOT, "MEMORY", "INDEX.json"), encoding="utf-8").read()
        mod.build(30)
        second = open(os.path.join(REPO_ROOT, "MEMORY", "INDEX.json"), encoding="utf-8").read()
        self.assertEqual(first, second)

    def test_index_has_no_timestamp(self):
        mod = load_builder()
        mod.build(30)
        data = json.load(open(os.path.join(REPO_ROOT, "MEMORY", "INDEX.json"), encoding="utf-8"))
        self.assertNotIn("generatedAt", data)
        self.assertIn("inputFingerprint", data)


class TestBuilderDoesNotRewriteTruth(unittest.TestCase):
    """The builder reports; the human decides. It must never touch the ledger."""

    def test_digest_is_unchanged_by_build(self):
        before = digest_hash()
        load_builder().build(30)
        self.assertEqual(before, digest_hash())

    def test_generated_files_carry_marker(self):
        load_builder().build(30)
        for name in ("INDEX.json", "HEALTH.md"):
            body = open(os.path.join(REPO_ROOT, "MEMORY", name), encoding="utf-8").read()
            self.assertIn("generated by scripts/memory_build.py", body)


class TestBuilderFindings(unittest.TestCase):
    def test_health_reports_all_four_rot_modes(self):
        load_builder().build(30)
        body = open(os.path.join(REPO_ROOT, "MEMORY", "HEALTH.md"), encoding="utf-8").read()
        for heading in ("Orphans", "Stale", "Unsourced numbers", "Archive candidates"):
            self.assertIn(f"## {heading}", body)

    def test_every_digest_number_has_an_artifact(self):
        """No claim in the digest may be a rumour."""
        mod = load_builder()
        artifacts = mod.scan(30)
        self.assertEqual(mod.find_unsourced(artifacts), [])

    def test_no_orphan_prose(self):
        mod = load_builder()
        artifacts = mod.scan(30)
        self.assertEqual(mod.find_orphans(artifacts), [])


if __name__ == "__main__":
    unittest.main()
